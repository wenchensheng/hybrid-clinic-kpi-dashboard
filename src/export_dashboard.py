"""Precompute compact JSON aggregates for the static GitHub Pages dashboard (docs/)."""
from __future__ import annotations

import json
import sqlite3
from pathlib import Path

import pandas as pd

from findings import compute

ROOT = Path(__file__).resolve().parents[1]
DB = ROOT / "data" / "processed" / "clinic_kpi.db"
OUT = ROOT / "docs" / "data"

CUBE_SQL = """
SELECT substr(a.appt_date, 1, 7) AS month, a.clinic_id AS clinic, a.modality_scheduled AS modality,
       p.rurality, p.age_band,
       COUNT(*)                                            AS scheduled,
       SUM(a.status = 'completed')                         AS completed,
       SUM(a.status = 'no_show')                           AS no_show,
       SUM(a.status = 'cancelled')                         AS cancelled,
       SUM(CASE WHEN a.visit_type <> 'acute' THEN a.lead_days ELSE 0 END) AS lead_sum,
       SUM(a.visit_type <> 'acute')                        AS lead_n,
       SUM(a.visit_type <> 'acute' AND a.lead_days > 14)   AS lead_over14,
       SUM(a.video_fallback_to_audio)                      AS fallback,
       SUM(a.inperson_followup_14d)                        AS followup14,
       ROUND(SUM(a.charge_amount), 2)                      AS charges,
       SUM(a.claim_denied)                                 AS denied,
       ROUND(SUM(a.charge_amount * a.claim_denied), 2)     AS denied_charges,
       SUM(a.video_fallback_to_audio * a.claim_denied)     AS fallback_denied
FROM appointments a JOIN patients p USING (patient_id)
GROUP BY 1, 2, 3, 4, 5
"""
UTIL_SQL = """
SELECT s.month, s.provider_id AS provider, pr.clinic_id AS clinic, pr.role, s.slots,
       COALESCE(v.completed, 0) AS completed, COALESCE(v.booked, 0) AS booked
FROM (SELECT provider_id, substr(session_date, 1, 7) AS month, SUM(slots) AS slots
      FROM provider_sessions GROUP BY 1, 2) s
JOIN providers pr USING (provider_id)
LEFT JOIN (SELECT provider_id, substr(appt_date, 1, 7) AS month, COUNT(*) AS booked,
                  SUM(status = 'completed') AS completed
           FROM appointments GROUP BY 1, 2) v USING (provider_id, month)
"""


def columnar(df: pd.DataFrame) -> dict:
    return {c: df[c].tolist() for c in df.columns}


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    con = sqlite3.connect(DB)
    cube = pd.read_sql_query(CUBE_SQL, con)
    util = pd.read_sql_query(UTIL_SQL, con)
    clinics = pd.read_sql_query("SELECT * FROM clinics ORDER BY clinic_id", con)
    con.close()
    cms = pd.read_csv(ROOT / "data" / "external" / "cms_telehealth_national.csv")
    cms = cms[cms.quarter != "Overall"]
    payload = {
        "meta": {"note": "SYNTHETIC clinic data generated by src/generate_synthetic.py; CMS data is public.",
                 "months": sorted(cube.month.unique().tolist())},
        "clinics": clinics.to_dict(orient="records"),
        "cube": columnar(cube),
        "utilization": columnar(util),
        "cms": columnar(cms[["geography", "year", "quarter", "dimension", "segment", "pct_using_telehealth"]]),
        "findings": compute(DB),
    }
    path = OUT / "dashboard.json"
    path.write_text(json.dumps(payload, separators=(",", ":")))
    print(f"[dashboard] {len(cube):,} cube rows -> {path.relative_to(ROOT)} ({path.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
